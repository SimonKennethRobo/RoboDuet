def main() -> None:
    ap = argparse.ArgumentParser(
        description='Velocity-sampled, length-controlled full-pose trajectory generator.')
    ap.add_argument('--config', default='configs/trajectory_generation.yaml')
    ap.add_argument('--show', action='store_true',
                    help='display the 3D plot interactively (rotate / zoom)')
    ap.add_argument('--D', type=float, default=None,
                    help='generate only this single difficulty (pair with --show)')
    args = ap.parse_args()

    cfg = load_generation_config(args.config)

    gen_cfg  = cfg.get('generator', {})
    vel_cfg  = cfg['velocity']
    att_cfg  = cfg.get('attitude', {})
    out_cfg  = cfg.get('output', {})
    viz_cfg  = cfg.get('visualization', {})

    N   = int(gen_cfg.get('N',  5000))
    K   = int(gen_cfg.get('K',  300))
    DT  = float(gen_cfg.get('dt', 0.01))
    dev = str(gen_cfg.get('device', 'cuda'))
    device = dev if (dev != 'cuda' or torch.cuda.is_available()) else 'cpu'
    length_range = (float(vel_cfg['length_min']), float(vel_cfg['length_max']))

    # ── load the pre-computed fields ──────────────────────────────────────────
    fields_pt = Path(gen_cfg.get('fields_path', 'runs/langevin/precomputed_fields.pt'))
    if not fields_pt.exists():
        raise FileNotFoundError(
            f"Pre-computed fields not found at {fields_pt}\n"
            f"Run first:  conda run -n roboduet python scripts/langevin_field_gen.py")
    ckpt = torch.load(fields_pt, map_location='cpu', weights_only=False)
    for key in ('field_static', 'field_dynamic', 'field_body', 'field_orient'):
        if key not in ckpt:
            raise KeyError(f"{key} missing from {fields_pt} — re-run langevin_field_gen.py")
    grid_half = float(ckpt['grid_half'])
    fg = ltg.FieldGenerator(
        field_static    = ckpt['field_static'],
        field_dynamic   = ckpt['field_dynamic'],
        field_body      = ckpt['field_body'],
        grid_half       = grid_half,
        ground_z        = float(ckpt['ground_z']),
        device          = device,
        body_box_center = ckpt.get('body_box_center', (0.0, 0.0, 0.0)),
        body_box_size   = ckpt.get('body_box_size', (0.3762, 0.13, 0.114)),
    )
    field_orient  = ckpt['field_orient']
    orient_limits = list(ckpt.get('orient_limits', (1.4137, 1.0472, 1.3090)))

    save_dir = Path(out_cfg.get('save_dir', 'runs/test_velocity'))
    save_dir.mkdir(parents=True, exist_ok=True)
    pt_pre   = out_cfg.get('pt_prefix', 'testvel')
    plot_pre = out_cfg.get('plot_prefix', 'testvel')

    raw_d = cfg.get('difficulties', [0.0, 0.5, 1.0])
    difficulties = [raw_d] if isinstance(raw_d, (int, float)) else list(raw_d)
    if args.D is not None:                       # --D : run/show just one difficulty
        difficulties = [args.D]

    print(f"Device     : {device.upper()}")
    print(f"Particles  : {N}  |  Steps : {K}  |  dt : {DT} s")
    print(f"Curriculum : D≤{vel_cfg['point_max']:g} point · "
          f"length L(D)∈[{length_range[0]}, {length_range[1]}] m  ·  "
          f"curviness ∝ D\n")

    for D in difficulties:
        D = float(D)
        print(f"── Difficulty D = {D:.2f}  {'─'*44}")
        # ── position ──────────────────────────────────────────────────────────
        sim = VelocityTrajectorySimulator(fg, D, N, K, DT, vel_cfg, device)
        history_x, history_v = sim.simulate()

        # ── attitude (position-conditioned feasible orientation) ──────────────
        att = ptg.AttitudeSimulator(D, sim.stage, N, K, DT, att_cfg,
                                    field_orient, grid_half, orient_limits, device)
        history_euler = att.simulate(history_x)
        history_quat  = ptg.euler_to_quat(history_euler)
        history_abg   = ptg.quat_to_abg(history_quat)

        # ── validity / curriculum check ──────────────────────────────────────
        flat = history_x.reshape(-1, 3)
        sv, _ = fg.query_field(fg._field_curr, flat)
        bv, _ = fg.query_field(fg.field_body,  flat)
        if sim.stage != 'point':
            achieved = (history_x[:, 1:] - history_x[:, :-1]).norm(dim=-1).sum(dim=1)
            err = (achieved - sim.target_length).abs().max().item()
            # Net XY displacement & XY bounding-box span — quantifies how far
            # the trajectory travels in the floor plane.  This is the metric
            # that tells you the dog's BASE has to translate to follow:
            # a long path that folds in on itself has tiny net XY, while a
            # drift-anchored path scales net XY with L.
            xy = history_x[:, :, :2]
            net_xy = (xy[:, -1] - xy[:, 0]).norm(dim=-1)                   # [N]
            span_xy = (xy.max(dim=1).values - xy.min(dim=1).values).norm(dim=-1)
            ratio = (net_xy / achieved.clamp(min=1e-6)).mean().item()
            print(f"  length  : mean={achieved.mean():.3f} m  "
                  f"[{achieved.min():.2f}, {achieved.max():.2f}]  "
                  f"max|err|={err*1e3:.3f} mm")
            print(f"  XY span : net displacement mean={net_xy.mean():.2f} m "
                  f"[{net_xy.min():.2f}, {net_xy.max():.2f}]  ·  "
                  f"bbox diag mean={span_xy.mean():.2f} m  ·  "
                  f"net/L = {ratio*100:.0f}%  (⇒ base must travel ≥ net XY)")
        cmd_report = command_limit_report(history_x, vel_cfg)
        if cmd_report:
            print(cmd_report)
        grid_out = (history_x.abs() > fg.gh).any(dim=-1).float().mean().item() * 100
        if sim.stage == 'outreach':
            print(f"  grid    : {grid_out:.2f}% of samples outside SDF grid (should be ~0)")
        if sim.stage == 'outreach':
            # outreach trajectories roam freely; each must have SOME hard content
            svN, bvN = sv.reshape(N, K), bv.reshape(N, K)
            hard = (svN > 0.0) | (bvN < 0.0)              # out of arm reach OR in the body
            frac = hard.float().mean(dim=1) * 100         # [N] per-trajectory hard %
            out_pct  = (sv > 0.0).float().mean().item() * 100
            body_pct = (bv < 0.0).float().mean().item() * 100
            print(f"  free-roam : {out_pct:.0f}% of all points out of arm reach · "
                  f"{body_pct:.0f}% inside the body")
            print(f"  hard part : every traj {frac.min().item():.0f}–{frac.max().item():.0f}% "
                  f"unfollowable (mean {frac.mean().item():.0f}%)  ⇒  base motion required")
        else:
            pct_ws   = (sv < 0.02).float().mean().item() * 100
            pct_body = (bv > 0.0).float().mean().item() * 100
            print(f"  valid   : {pct_ws:.1f}% in workspace · {pct_body:.1f}% off body")

        d_tag   = f'D{int(round(D * 100)):03d}'
        pt_path = save_dir / f'{pt_pre}_{d_tag}.pt'
        torch.save({'history_x':     history_x.cpu(),
                    'history_v':     history_v.cpu(),
                    'history_lpy':   xyz_to_lpy(history_x).cpu(),
                    'history_euler': history_euler.cpu(),
                    'history_quat':  history_quat.cpu(),
                    'history_abg':   history_abg.cpu(),
                    'target_length': sim.target_length.cpu(),
                    'D': D, 'N': N, 'K_STEPS': K, 'DT': DT, 'stage': sim.stage}, pt_path)
        print(f"  Saved → {pt_path}")

        visualize(sim, history_x, history_v, history_quat, D, length_range,
                  viz_cfg, save_path=str(save_dir / f'{plot_pre}_{d_tag}.png'),
                  show=args.show)
        print()

    print("Done.")


if __name__ == '__main__':
    main()
