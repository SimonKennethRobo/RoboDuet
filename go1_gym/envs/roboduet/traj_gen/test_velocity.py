#!/usr/bin/env python3
"""
Velocity-Sampled Full-Pose Trajectory Generator  —  difficulty-scaled

Trajectories are built from a SAMPLED velocity so the path length is exact and
stable (unlike the goal-attractor generators, where length only emerges).

Curriculum  (difficulty D — same spirit as langevin_traj_gen.py)
────────────────────────────────────────────────────────────────
  D ≤ point_max        →  a single held POINT  (position + held orientation)
  D small  (just above) →  SHORT + STRAIGHT path  (length ≈ length_min, ~no wander)
  D large              →  LONG + CURVY path      (length ≈ length_max, big wander)

Both the length AND the curviness scale with D:
  * length :  L(D) = lerp(length_min, length_max, t),  t = (D−point_max)/(1−point_max)
              — a short path fits straight; a long one must fold (⇒ curvy).
  * wander :  turn_sigma = D^wander_exp · disturb

Length is EXACT: a trapezoidal speed profile (rest→cruise→rest) is scaled so its
time-integral equals L; only the DIRECTION is steered (wander + bounded barrier,
grid, and command-cone avoidance), never the speed.

Attitude  (see pose_traj_gen.py)
────────────────────────────────
The EE orientation is generated by the position-conditioned reachable-orientation
tracker (pose_traj_gen.AttitudeSimulator): every pose is jointly feasible, and
the orientation difficulty scales with D as well (D small → near the feasible
mean, D large → more orientation variation).

Output per difficulty:
  testvel_D###.pt   — history_x/v [N,K,3], history_euler/quat/abg, target_length …
  testvel_D###.png  — 3D trajectories + EE triads + length & turn-angle stats

Usage:
  conda run -n roboduet python scripts/langevin_field_gen.py     # fields, once
  conda run -n roboduet python scripts/test_velocity.py
  conda run -n roboduet python scripts/test_velocity.py --show
"""

