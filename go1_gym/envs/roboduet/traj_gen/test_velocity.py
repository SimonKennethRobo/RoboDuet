def visualize(sim, history_x, history_v, history_quat, D, length_range,
              viz_cfg, save_path, show):
    """3D trajectories + EE-frame triads  |  length histogram  |  turn-angle stats."""
    hist = history_x.cpu().numpy()
    vel  = history_v.cpu().numpy()
    quat = history_quat.cpu().numpy()
    L    = sim.target_length.cpu().numpy()
    N, K, _ = hist.shape
    fg = sim.fg
    gh, ground_z = fg.gh, fg.ground_z
    Lmin, Lmax = length_range
    n_traj   = min(int(viz_cfg.get('n_trajectories', 10)), N)
    n_triads = int(viz_cfg.get('n_triads', 7))
    tlen     = float(viz_cfg.get('triad_len', 0.10))

    rng    = np.random.default_rng(0)
    chosen = rng.choice(N, size=n_traj, replace=False)

    fig = plt.figure(figsize=(21, 7))
    ax  = fig.add_subplot(1, 3, 1, projection='3d')
    axL = fig.add_subplot(1, 3, 2)
    axT = fig.add_subplot(1, 3, 3)

    # ── 3D trajectories + EE triads ───────────────────────────────────────────
    gs = np.linspace(-gh * 0.95, gh * 0.95, 6)
    GX, GY = np.meshgrid(gs, gs)
    ax.plot_surface(GX, GY, np.full_like(GX, ground_z), alpha=0.08,
                    color='saddlebrown', linewidth=0)
    sdf = fg._field_curr[0, 0].cpu().numpy()
    lin = np.linspace(-gh, gh, fg.grid_res)
    iz, iy, ix = np.where(np.abs(sdf) < 0.04)
    if len(iz) > 2000:
        s = rng.choice(len(iz), 2000, replace=False)
        iz, iy, ix = iz[s], iy[s], ix[s]
    ax.scatter(lin[ix], lin[iy], lin[iz], s=0.6, alpha=0.04, color='steelblue')
    ltg._draw_box(ax, fg.body_box_center, fg.body_box_size, color='dimgray', alpha=0.20)

    span = max(Lmax - Lmin, 1e-6)
    basis = torch.eye(3)
    tri_steps = np.unique(np.linspace(0, K - 1, n_triads).astype(int))
    for idx in chosen:
        tr  = hist[idx]
        col = cm.viridis(float((L[idx] - Lmin) / span)) if sim.stage != 'point' \
              else cm.viridis(0.5)
        ax.plot(tr[:, 0], tr[:, 1], tr[:, 2], color=col, lw=1.1, alpha=0.9, zorder=10)
        ax.scatter(*tr[0], color=col, s=26, marker='o', edgecolors='k',
                   linewidths=0.3, zorder=11)
        q_sel = torch.from_numpy(quat[idx, tri_steps]).float()       # [T,4]
        p_sel = tr[tri_steps]
        for a, acol in enumerate(['red', 'green', 'blue']):          # EE X/Y/Z
            dvec = ptg.quat_apply(q_sel, basis[a]).numpy() * tlen
            for m in range(len(tri_steps)):
                ax.plot([p_sel[m, 0], p_sel[m, 0] + dvec[m, 0]],
                        [p_sel[m, 1], p_sel[m, 1] + dvec[m, 1]],
                        [p_sel[m, 2], p_sel[m, 2] + dvec[m, 2]],
                        color=acol, lw=1.3, alpha=0.9, zorder=12)
    ax.scatter(0, 0, 0, color='red', s=90, marker='o', edgecolors='darkred', zorder=20)
    ax.set_xlabel('X (m)'); ax.set_ylabel('Y (m)'); ax.set_zlabel('Z (m)')
    # outreach trajectories leave the workspace — widen the box to fit them
    lim = max(gh * 0.98, float(np.abs(hist[:, :, :2]).max()) * 1.05)
    zhi = max(gh * 0.98, float(hist[:, :, 2].max()) * 1.05)
    ax.set_xlim(-lim, lim); ax.set_ylim(-lim, lim); ax.set_zlim(ground_z - 0.05, zhi)
    try:
        ax.set_box_aspect([1, 1, 1])
    except (AttributeError, TypeError):
        pass
    ax.set_title(f'Velocity-Sampled Full-Pose Trajectories  ·  D = {D:.2f}  '
                 f'·  stage: {sim.stage}\n'
                 f'N = {N}  ·  colour = path length  ·  RGB triads = EE attitude',
                 fontsize=10, fontweight='bold', pad=8)

    # ── achieved path-length histogram ────────────────────────────────────────
    step_len = np.linalg.norm(np.diff(hist, axis=1), axis=-1)
    achieved = step_len.sum(axis=1)
    axL.hist(achieved, bins=30, color='mediumseagreen', edgecolor='k', alpha=0.85)
    axL.axvline(Lmin, color='red', ls='--', lw=0.9)
    axL.axvline(Lmax, color='red', ls='--', lw=0.9)
    axL.set_xlabel('achieved path length (m)'); axL.set_ylabel('trajectories')
    axL.set_title(f'Path length  ·  mean={achieved.mean():.2f}  '
                  f'[{achieved.min():.2f}, {achieved.max():.2f}] m\n'
                  f'max |achieved − target| = {np.abs(achieved - L).max()*1e3:.2f} mm',
                  fontsize=10, fontweight='bold')
    axL.grid(alpha=0.3)

    # ── per-step turn-angle distribution (straightness ↔ disturbance) ────────
    sp = np.linalg.norm(vel, axis=-1)
    vn = vel / np.clip(sp[..., None], 1e-9, None)
    cos = np.clip(np.sum(vn[:, 1:] * vn[:, :-1], axis=-1), -1, 1)
    ang = np.degrees(np.arccos(cos))
    moving = (sp[:, 1:] > 0.1) & (sp[:, :-1] > 0.1)
    a = ang[moving]
    if a.size > 0:
        axT.hist(a, bins=40, color='slateblue', edgecolor='k', alpha=0.85)
        axT.set_title(f'Direction smoothness  ·  D = {D:.2f}\n'
                      f'mean={a.mean():.2f}°  p99={np.percentile(a,99):.2f}°  '
                      f'max={a.max():.1f}°', fontsize=10, fontweight='bold')
    else:
        axT.text(0.5, 0.5, 'point stage — no motion', ha='center', va='center',
                 transform=axT.transAxes, fontsize=11)
        axT.set_title(f'Direction smoothness  ·  D = {D:.2f}',
                      fontsize=10, fontweight='bold')
    axT.set_xlabel('per-step turn angle (deg)'); axT.set_ylabel('steps')
    axT.grid(alpha=0.3)

    plt.tight_layout()
    if save_path:
        os.makedirs(os.path.dirname(save_path) or '.', exist_ok=True)
        plt.savefig(save_path, dpi=140, bbox_inches='tight')
        print(f"  Saved → {save_path}")
    if show:
        plt.show()
    plt.close(fig)


# ─────────────────────────────────────────────────────────────────────────────
# Main
