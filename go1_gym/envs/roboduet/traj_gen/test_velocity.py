def load_generation_config(path: str) -> dict:
    with open(path) as f:
        cfg = yaml.safe_load(f)
    if 'generator' in cfg:
        return cfg

    # Backward compatibility for the older configs/test_velocity.yaml shape.
    # The canonical config is now configs/trajectory_generation.yaml.
    if 'base_config' not in cfg:
        raise KeyError("config must contain either 'generator' or 'base_config'")
    base = ltg.load_config(cfg['base_config'])
    lc = base.get('langevin', {})
    gc = base.get('generator', {})
    fg = base.get('field_gen', {})
    fields_path = Path(fg.get('save_dir', 'runs/langevin')) / \
                  fg.get('fields_filename', 'precomputed_fields.pt')
    merged = dict(cfg)
    merged['generator'] = {
        'N': lc.get('N', 5000),
        'K': lc.get('K', 300),
        'dt': lc.get('dt', 0.01),
        'device': gc.get('device', 'cuda'),
        'fields_path': str(fields_path),
    }
    return merged


def command_limit_report(history_x: torch.Tensor, vel_cfg: dict) -> str:
    limits = vel_cfg.get('command_limits')
    if not limits:
        return ''
    lpy = xyz_to_lpy(history_x.reshape(-1, 3))
    names = ('l', 'p', 'y')
    out_parts = []
    any_out = torch.zeros(lpy.shape[0], dtype=torch.bool, device=lpy.device)
    for i, key in enumerate(names):
        if key not in limits:
            continue
        lo, hi = float(limits[key][0]), float(limits[key][1])
        out = (lpy[:, i] < lo) | (lpy[:, i] > hi)
        any_out |= out
        out_parts.append(f"{key}_out={out.float().mean().item()*100:.1f}%")
    if not out_parts:
        return ''
    return f"  command : any_out={any_out.float().mean().item()*100:.1f}%  " + \
           "  ".join(out_parts)


